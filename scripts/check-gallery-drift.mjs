import {chromium} from "playwright"
import assert from "node:assert/strict"
const browser=await chromium.launch()
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:"no-preference"})
await page.addInitScript(()=>sessionStorage.setItem("intro-seen","1"))
await new Promise(resolve=>setTimeout(resolve,1000))
try {
 await page.goto(`${process.env.BASE_URL||"http://127.0.0.1:3020"}/about`,{waitUntil:"domcontentloaded"})
 const rail=page.locator('[aria-label^="Photo wall."]')
 const position=()=>rail.evaluate(el=>el.scrollLeft)
 await rail.scrollIntoViewIfNeeded()
 await page.mouse.move(0,0)
 let before=await position()
 await page.waitForTimeout(1400)
 assert.ok(await position()>before+10,"gallery drifts while idle")
 await rail.hover()
 before=await position();await page.waitForTimeout(600)
 assert.ok(Math.abs(await position()-before)<=1,"hover pauses drift")
 await page.mouse.move(0,0)
 await rail.focus()
 before=await position();await page.waitForTimeout(600)
 assert.ok(Math.abs(await position()-before)<=1,"keyboard focus pauses drift")
 await page.getByRole('button',{name:'Pause drift'}).click()
 before=await position();await page.waitForTimeout(600)
 assert.ok(Math.abs(await position()-before)<=1,"manual pause holds position")
 await page.getByRole('button',{name:'Resume drift'}).click()
 await page.mouse.move(0,0)
 before=await position();await page.waitForTimeout(1000)
 assert.ok(Math.abs(await position()-before)>8,"resume restarts drift")
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.getByText('Motion off · drag to explore').waitFor()
 before=await position();await page.waitForTimeout(600)
 assert.ok(Math.abs(await position()-before)<=1,"reduced motion stops drift")
 assert.equal(await page.locator('button[aria-label^="Enlarge photo:"]').count(),15)
 console.log('Idle movement, hover/focus/manual pauses, resume, reduced motion and 15-photo preservation passed')
} finally {await browser.close()}
